"""Evaluation: the layers of [`evals.md`](../../docs/evals.md).

What is here is Track D's self-contained half — layer 0 (regression scalars),
layer 2 (the league and the cost-versus-Elo curve, §5.4) and layer 3
(diagnostics). None of them needs a second process, an opening book, or an
external engine: layer 2's opponents are our own past checkpoints and its openings
are generated from the rules. Layers 0 and 3 are the frequent ones — they run on
every checkpoint and they never block; layer 2 runs over a finished run.

Two things this package is careful about.

**Evaluation output never flows backwards** (`evals.md` §2). Nothing here returns
a value that is meant to select a checkpoint, stop a run, or pick a
hyperparameter. The only permitted feedback is abort-on-divergence, which is a
liveness check and carries no chess opinion.

**The rule suites carry no chess opinion either.** Every suite in `suites.py` is
generated by our own move generator from random legal play, and its answer key is
a *terminal code* — checkmate, stalemate, threefold — never a material count or an
evaluation. "Mate beats stalemate" is a rule; "a knight is worth three pawns" is
an opinion, and no suite here needs one. That is what keeps them usable during
training rather than only after it.

The external puzzle set in `puzzles.py` is the one exception, and it is data, not
code: it is inside the boundary only because §2 puts *evaluation* outside it.
"""

